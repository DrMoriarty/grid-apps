/**
 * CAM stock removal model (Phase 1 skeleton).
 *
 * Maintains a per-widget "removed top" heightmap: for each grid node over the
 * widget bounds it stores the z of the material surface *after* all recorded
 * tool sweeps. Untouched nodes hold the stock top z, so the map doubles as
 * "current material top". Served from a SharedArrayBuffer (same pattern as
 * `widget.topo.data` in topo3.js) so worker code and main thread can share it.
 *
 * Data model conventions:
 *   - grid node (gx,gy) maps to world (minX + gx*resolution, minY + gy*resolution),
 *     same convention as the topo raster (see topo3.js crossR_sync comment);
 *   - cell index = gx * stepsY + gy, same as Probe.toolAtZ;
 *   - tool profiles are raster profiles generated by
 *     `Tool.generateProfile(resolution)` at THIS model's resolution, i.e.
 *     profile offsets are in grid pixels with dz <= 0 below the tool tip,
 *     identical to what Probe consumes.
 *
 * Recording a sweep is the inverse of Probe.toolAtZ (topo3.js:826-855).
 * toolAtZ answers "what tip z does terrain force" via the constraint
 * T >= dz + terrain for every profile point. Inverting it, a tool with tip
 * at T leaves terrain at T - dz in every covered cell (dz <= 0 is the
 * profile point's depth below the tip, so T - dz is the cutter underside
 * z at that offset): flat endmill -> T everywhere in the flute disc, ball
 * -> a bowl, shaft points (dz = -flute_len, above the tip) write above T
 * and thus never cut. Folding a sweep into the grid keeps the deepest
 * engagement per cell: data[cell] = min(data[cell], tipz - dz), the same
 * profile convolution loop as toolAtZ with max/min flipped.
 *
 * Scope note: this is skeleton + API only. Consumers (ops recording sweeps,
 * views querying removal) are wired in follow-up tasks.
 */

// ops whose motion happens in rotated stock space: their camLines cannot be
// projected onto the XY heightmap, so recording one marks the model invalid
// and consumers must fall back to current (model-less) behavior
const ROTARY_OPS = new Set(['index', 'lathe']);

// bilinear boundary snap epsilon (fraction of a cell)
const EPS = 1e-6;

// coarse block-max tiling of the heightmap used for sound air-stamp
// skipping (see #regionAir): the node lattice is tiled into
// BLOCK_SIZE x BLOCK_SIZE blocks and `blockMax` over-approximates the
// max data value per block, so a few dozen block reads can prove a
// whole stamp footprint sits over air. small blocks (4x4 nodes) keep the
// block bound tight next to material boundaries, where a coarser tile
// would mix cleared and untouched cells and defeat skipping; power of
// two so block index computation is a shift
const BLOCK_SHIFT = 2;
const BLOCK_SIZE = 1 << BLOCK_SHIFT;

// profile points are bucketed by write depth (dz) for the air-skip test;
// more distinct depths than this (continuous ball/taper profiles) collapse
// into a single conservative group
const AIR_GROUP_MAX = 4;

// tolerance for "material top at or below tip z" comparisons in
// clearedRegion (mm): z values converge on the same plane through
// different lerp/add paths, so exact equality is unreliable; anything
// within this margin counts as already swept
const CLEAR_EPS = 0.001;

// op types whose sweeps are folded into the stock model (see
// recordAreaSweep): their tool footprints define the finest detail the
// grid must resolve, so only these ops' tools drive auto-resolution
const SWEEP_OPS = new Set(['rough', 'outline', 'trace', 'pocket', 'contour']);

// monotone-ish ms clock (workers and main thread both have performance;
// Date.now fallback for exotic environments)
const time_now = () =>
    (typeof performance !== 'undefined' && performance.now)
        ? performance.now()
        : Date.now();

// hybrid auto-resolution clamp bounds (mm per grid cell). lower bound
// keeps stamp footprints at a few pixels for sub-1mm tools (they ride
// the clamp and record coarser sweeps than their diameter); upper bound
// keeps stamps of large tools from covering huge swaths of nothing
const STOCK_RES_MIN = 0.2;
const STOCK_RES_MAX = 1.0;
// fallback when no sweep op has a usable tool (empty/disabled op list)
const STOCK_RES_DEFAULT = 0.5;
// size cap: auto-resolution is coarsened so neither lattice axis exceeds
// this many nodes, bounding heightmap memory and #strike cost on big stocks
const STOCK_STEPS_MAX = 800;

export class StockModel {

    /**
     * debug reference mode: when true, air-stamp skipping is disabled and
     * every stamp runs its full footprint min-merge (the pre-skip semantics).
     * used by soundness tests to prove the skip is byte-exact against
     * unconditional stamping on real pipeline toolpaths.
     * @type {boolean}
     */
    static naiveStamps = false;

    /**
     * @param {Object} opt
     * @param {Widget} opt.widget owning widget (for cache attachment by caller)
     * @param {Object} opt.bounds widget bounding box {min:{x,y,z}, max:{x,y,z}}
     * @param {number} [opt.resolution] grid resolution in mm; takes precedence
     *   over every other source (computed by `stockResolution()` for getStockModel)
     * @param {number} [opt.tolerance] grid resolution in mm; when 0/undefined
     *   and no opt.resolution, derived from animation mesh density using the
     *   topo3.js:46 formula (legacy path, kept for direct constructions)
     * @param {number} opt.stockTop world z of the stock top surface
     * @param {number} [opt.stockBottom] world z of the stock bottom surface
     * @param {string} [opt.fingerprint] cache validity fingerprint
     */
    constructor(opt) {
        const bounds = opt.bounds;
        const boundsX = bounds.max.x - bounds.min.x;
        const boundsY = bounds.max.y - bounds.min.y;
        const tolerance = opt.tolerance > 0 ? opt.tolerance : 0;

        // resolution source precedence: explicit opt.resolution (decoupled
        // from animesh, see stockResolution), then tolerance, then the
        // legacy topo3.js:46 formula (animesh = 100 * 2500)
        const animesh = parseInt(opt.animesh || 100) * 2500;
        const resolution = (opt.resolution > 0
            ? opt.resolution
            : tolerance
                ? tolerance
                : 1 / Math.sqrt(animesh / (boundsX * boundsY))
        ).round(5);

        // +1 so the node lattice covers maxX/maxY exactly
        const stepsX = Math.ceil(boundsX / resolution) + 1;
        const stepsY = Math.ceil(boundsY / resolution) + 1;

        this.widget = opt.widget;
        this.bounds = bounds;
        this.minX = bounds.min.x;
        this.minY = bounds.min.y;
        this.tolerance = tolerance;
        this.resolution = resolution;
        this.stepsX = stepsX;
        this.stepsY = stepsY;
        this.stockTop = opt.stockTop;
        this.stockBottom = opt.stockBottom;
        this.fingerprint = opt.fingerprint;

        /** validity flag: false once a rotary op sweep was recorded */
        this.valid = true;

        /**
         * sweep journal: raw records for future visualizations (Phase 3).
         * each record: { seq, type, mode, rename, thru, tool, profile,
         *                camLines, down, leave, leave_z, ov_topz, ov_botz,
         *                valid }
         * @type {Array<Object>}
         */
        this.swaps = [];

        // removed-top heightmap, initialized to full stock
        this.data = new Float32Array(new SharedArrayBuffer(stepsX * stepsY * 4));
        this.data.fill(opt.stockTop);

        // block-max grid over `data` for air-stamp skipping. invariant:
        // blockMax[b] >= max(data over block b) at all times -- exact right
        // after #refreshBlocks, stale (too high) once writes lower nodes.
        // stale bounds stay sound (an over-estimate can only suppress skips,
        // never enable a wrong one); `blockDirty` flags blocks whose bound
        // must be recomputed to restore tightness, `dirtyBlocks` lists them
        // so refresh touches only written-to blocks
        this.blocksX = Math.ceil(stepsX / BLOCK_SIZE);
        this.blocksY = Math.ceil(stepsY / BLOCK_SIZE);
        this.blockMax = new Float32Array(this.blocksX * this.blocksY)
            .fill(opt.stockTop);
        this.blockDirty = new Uint8Array(this.blocksX * this.blocksY);
        this.dirtyBlocks = [];
    }

    /** world x,y -> fractional grid coords */
    toGridX(x) {
        return (x - this.minX) / this.resolution;
    }

    toGridY(y) {
        return (y - this.minY) / this.resolution;
    }

    /**
     * Record one toolpath sweep into the model.
     *
     * @param {Object} rec sweep descriptor:
     *   type     {string} op type ("rough", "outline", "index", ...)
     *   mode     {string} op sub-mode ("clear", "trace", ...) (optional)
     *   rename   {string} op rename / layer name (optional)
     *   thru     {boolean} trace passes through stock bottom (optional)
     *   tool     {Tool}   op tool (optional if profile given)
     *   profile  {Float32Array} raster tool profile from
     *            Tool.generateProfile(this.resolution).profile
     *   camLines {Array} polylines of points with x,y,z in world coords
     *   down, leave, leave_z, ov_topz, ov_botz {any} raw op params, journalled
     *   onProgress {Function} optional callback invoked periodically with a
     *     0..1 fraction of the sweep recording (not journalled)
     * @returns {Object} the journal record
     */
    recordSweep(rec) {
        const entry = {
            seq: this.swaps.length,
            type: rec.type,
            mode: rec.mode,
            rename: rec.rename,
            thru: rec.thru,
            tool: rec.tool,
            profile: rec.profile ?? rec.tool?.profile,
            camLines: rec.camLines,
            down: rec.down,
            leave: rec.leave,
            leave_z: rec.leave_z,
            ov_topz: rec.ov_topz,
            ov_botz: rec.ov_botz,
            valid: this.valid
        };
        this.swaps.push(entry);

        if (ROTARY_OPS.has(rec.type)) {
            // rotary motion cannot be folded into the XY heightmap:
            // mark invalid, keep the journal record, change nothing else
            this.valid = false;
            entry.valid = false;
            return entry;
        }

        const profile = entry.profile;
        if (!profile || !rec.camLines) {
            return entry;
        }

        // fold the sweep and journal the recording time (diagnostics; the
        // journal is the per-sweep record consumers may inspect)
        const t0 = time_now();
        this.#strike(rec.camLines, profile, rec.onProgress, rec.tool?.profileDim?.maxo);
        entry.strikeMs = time_now() - t0;
        return entry;
    }

    /**
     * Fold a set of world-space polylines through a tool profile into the
     * heightmap. Only milling motion removes material: tool positions whose
     * tip z is at or above the stock top remove nothing (plunges from above
     * only start cutting once below the surface, retracts/traverses never
     * touch). Tab/clamp lifts and ov_topz/ov_botz are already baked into
     * camLines by the time they are recorded, so no extra handling here.
     *
     * Stamp spacing along the path is derived from the tool profile's
     * horizontal radius in grid pixels: consecutive stamps one radius apart
     * still overlap by half their footprint diameter, so the swept band
     * stays gapless in its interior (neighboring passes at the op stepover
     * cover the rest). Sampling every `resolution` instead would stamp the
     * same footprint once per grid cell of travel — for stock-scale clears
     * (camRoughAll) that multiplies the work by ~tool-radius/resolution
     * (hundreds-fold at fine grid resolutions), turning slice into a hours-long
     * freeze. The only loss is a sub-radius fringe at the outer envelope of
     * the sweep where the disc boundary scallops between stamps; those
     * cells keep the stock top, which is the safe direction for every
     * consumer (skipclear/clearedRegion mask less, rapids stay higher).
     *
     * Air stamps are skipped soundly: a coarse block-max grid over the
     * heightmap proves "whole footprint already at or below tip z" with a
     * handful of reads, at segment granularity when an entire subdivision
     * run is over air and per stamp otherwise (see #regionAir). Skipped
     * stamps are exactly those whose min-merge would write nothing, so the
     * folded heightmap is identical to unconditional stamping. Stale block
     * bounds after writes only suppress skips (never enable wrong ones);
     * bounds are refreshed after each camLine.
     *
     * @param {Array} camLines polylines (Polygon or point array, points with x,y,z)
     * @param {Float32Array} profile raster tool profile (grid-pixel offsets)
     * @param {Function} [onProgress] optional callback with a 0..1 fraction
     * @param {number} [radHint] cutting footprint radius in grid pixels
     *   (Tool.profileDim.maxo). fallback scans the profile, which may
     *   include shaft points (never cutting) and so errs denser
     */
    #strike(camLines, profile, onProgress, radHint) {
        const { stockTop, resolution } = this;
        // horizontal radius of the cutting footprint in grid pixels, used
        // as the stamp spacing below (maxo covers flute points; shaft
        // points never write, see #stamp)
        let radpx = 0;
        if (radHint > 0) {
            radpx = radHint;
        } else {
            for (let i = 0; i < profile.length; i += 3) {
                const tx = Math.abs(profile[i]),
                    ty = Math.abs(profile[i + 1]);
                if (tx > radpx) {
                    radpx = tx;
                }
                if (ty > radpx) {
                    radpx = ty;
                }
            }
        }
        const maxStep = Math.max(resolution, Math.round(radpx) * resolution);
        // shallowest tip z this sweep can stamp: profile points whose write
        // (tipz - dz, tipz >= zmin) can never dip below the stock top never
        // lower any cell and are excluded from the air-skip groups
        let zmin = Infinity;
        for (let line of camLines) {
            const pts = line.points || line;
            if (!pts) {
                continue;
            }
            for (let i = 0; i < pts.length; i++) {
                if (pts[i].z < zmin) {
                    zmin = pts[i].z;
                }
            }
        }
        if (zmin === Infinity) {
            zmin = stockTop;
        }
        const groups = profileAirGroups(profile, zmin, stockTop);
        // progress denominator: total path points (subdivided sample count
        // is always >= this, so the reported fraction is clamped)
        let total = 0;
        if (onProgress) {
            for (let line of camLines) {
                total += (line.points || line)?.length || 0;
            }
        }
        let done = 0,
            lineIdx = 0;
        for (let line of camLines) {
            lineIdx++;
            const pts = line.points || line;
            if (pts && pts.length > 0) {
                // single-point line (e.g. drill mark): stamp directly
                if (pts.length === 1) {
                    const p = pts[0];
                    done++;
                    if (p.z < stockTop) {
                        this.#stamp(p.x, p.y, p.z, profile, groups);
                    }
                } else {
                    let prev = pts[0];
                    for (let i = 1; i < pts.length; i++) {
                        const p = pts[i];
                        const dx = p.x - prev.x,
                            dy = p.y - prev.y,
                            dist = Math.sqrt(dx * dx + dy * dy),
                            // subdivide long segments so the swept surface
                            // has no gaps
                            n = Math.max(1, Math.ceil(dist / maxStep));
                        // segment-level air skip: stamp positions, and thus
                        // gx(t), gy(t), z(t), are linear (fp-monotone) in t
                        // between the interpolated endpoints, so every stamp
                        // it would make has its tip at or above the lower
                        // endpoint z and its nodes inside each group's
                        // endpoint node box. when the block-max bound proves
                        // every node of that box already sits at or below the
                        // group's shallowest write, no stamp of the segment
                        // can lower any cell and the entire subdivision loop
                        // is skipped. endpoints reuse the loop's own
                        // interpolation (prev + d*1) so the box matches the
                        // stamped arithmetic exactly
                        const xe = prev.x + dx,
                            ye = prev.y + dy,
                            ze = prev.z + (p.z - prev.z);
                        if (this.#groupsAir(
                            this.toGridX(Math.min(prev.x, xe)),
                            this.toGridX(Math.max(prev.x, xe)),
                            this.toGridY(Math.min(prev.y, ye)),
                            this.toGridY(Math.max(prev.y, ye)),
                            Math.min(prev.z, ze),
                            groups
                        )) {
                            done += n + 1;
                            prev = p;
                            continue;
                        }
                        for (let s = 0; s <= n; s++) {
                            const t = s / n,
                                z = prev.z + (p.z - prev.z) * t;
                            done++;
                            if (onProgress && (done & 16383) === 0) {
                                onProgress(Math.min(1, done / total));
                            }
                            // z filter: above the stock surface nothing is removed
                            if (z >= stockTop) {
                                continue;
                            }
                            this.#stamp(
                                prev.x + dx * t,
                                prev.y + dy * t,
                                z,
                                profile,
                                groups
                            );
                        }
                        prev = p;
                    }
                }
            }
            // periodically restore tight block-max bounds so air stretches
            // over ground cut earlier in this same sweep are detected;
            // amortized (every 64 lines) to keep the cutting phase cheap,
            // plus once at the end so the next recordSweep starts tight
            if ((lineIdx & 63) === 63) {
                this.#refreshBlocks();
            }
        }
        this.#refreshBlocks();
        if (onProgress) {
            onProgress(1);
        }
    }

    /**
     * Fold one tool position into the heightmap. Inverse of Probe.toolAtZ:
     * profile point (dx,dy,dz) covers grid node (gx+dx, gy+dy) and the
     * cutter underside there sits at tipz - dz (dz <= 0). The deepest
     * engagement wins per cell, so writes are min-merged into data.
     * tipz is already filtered against stockTop by the caller, and since
     * dz <= 0 for cutting points, a stamp can never write above stockTop.
     *
     * Sound air skip: a profile point lowers a cell only when the write
     * tipz - dz exceeds that cell's current value. Points are bucketed by
     * depth (`groups`, see profileAirGroups); for each group the stamp's
     * node box is exact (Math.round of the extreme offsets is monotone, so
     * the extreme offsets attain the extreme nodes) and the group's
     * shallowest write is tipz - dzMax. When the block-max bound proves
     * every node of the box sits at or below that shallowest write, no
     * point of the group can lower anything; when that holds for every
     * group, the footprint iteration is skipped entirely. This never
     * suppresses a lowering write: any cell some point would lower holds a
     * value > tipz - dz >= the group test threshold, which fails the test.
     *
     * @param {Array} groups profile depth groups from profileAirGroups
     */
    #stamp(x, y, tipz, profile, groups) {
        const { data, stepsX, stepsY, blockMax, blockDirty, blocksY, dirtyBlocks } = this;
        const gx = this.toGridX(x),
            gy = this.toGridY(y);
        if (this.#groupsAir(gx, gx, gy, gy, tipz, groups)) {
            return;
        }
        let i = 0;
        while (i < profile.length) {
            const tx = Math.round(profile[i++] + gx),
                ty = Math.round(profile[i++] + gy),
                tz = tipz - profile[i++];
            if (tx < 0 || tx >= stepsX || ty < 0 || ty >= stepsY) {
                continue;
            }
            const idx = tx * stepsY + ty;
            if (tz < data[idx]) {
                // lowering the block's max node makes the bound stale: flag
                // it for refresh (once per block until refreshed). lowering
                // any other node leaves the bound (an over-estimate of the
                // max) valid, so no flag is needed
                const b = ((tx >> BLOCK_SHIFT) * blocksY) + (ty >> BLOCK_SHIFT);
                if (!blockDirty[b] && data[idx] >= blockMax[b]) {
                    blockDirty[b] = 1;
                    dirtyBlocks.push(b);
                }
                data[idx] = tz;
            }
        }
    }

    /**
     * Sound "all groups air" test. `x0 <= x1` and `y0 <= y1` are fractional
     * grid coordinates bracketing every stamp position to test (a single
     * stamp when x0 == x1, a whole segment otherwise); `z` is a lower bound
     * on the tip z of those stamps. For each depth group the stamp node box
     * is [round(x0 + xoffMin), round(x1 + xoffMax)] (exact: Math.round is
     * monotone in its argument) and the group's shallowest possible write
     * is z - dzMax, so every node in the box sitting at or below that value
     * means no stamp position covered by the box can lower any cell.
     *
     * @returns {boolean} true when no stamp inside the box at tip >= z can
     *   lower any cell
     */
    #groupsAir(x0, x1, y0, y1, z, groups) {
        if (StockModel.naiveStamps || !groups.length) {
            return false;
        }
        for (let g of groups) {
            if (!this.#regionAir(
                Math.round(x0 + g.x0),
                Math.round(y0 + g.y0),
                Math.round(x1 + g.x1),
                Math.round(y1 + g.y1),
                z - g.dz
            )) {
                return false;
            }
        }
        return true;
    }

    /**
     * Sound "all air" test over an inclusive node-index bounding box: are
     * all lattice nodes in the box guaranteed to sit at or below `z`?
     *
     * Uses the block-max grid: each block intersecting the box contributes
     * an over-estimate of its nodes' max, so if every such bound is <= z
     * then every node in the box is <= z. A stale (too high) bound only
     * makes the test answer "not air" and falls back to plain stamping --
     * never the reverse -- which is what keeps the skip sound regardless
     * of when #refreshBlocks last ran. Box parts outside the lattice are
     * ignored (the stamp clips out-of-lattice nodes anyway).
     *
     * @param {number} nx0,ny0,nx1,ny1 inclusive node-index box (any order/
     *   range; may lie partly or wholly outside the lattice)
     * @param {number} z world z to test against
     * @returns {boolean} true when no stamp whose footprint fits the box
     *   can lower any cell at tip z
     */
    #regionAir(nx0, ny0, nx1, ny1, z) {
        const { stepsX, stepsY, blocksY, blockMax } = this;
        const bx0 = Math.max(0, nx0) >> BLOCK_SHIFT,
            by0 = Math.max(0, ny0) >> BLOCK_SHIFT,
            bx1 = Math.min(stepsX - 1, nx1) >> BLOCK_SHIFT,
            by1 = Math.min(stepsY - 1, ny1) >> BLOCK_SHIFT;
        for (let bx = bx0; bx <= bx1; bx++) {
            const row = bx * blocksY;
            for (let by = by0; by <= by1; by++) {
                if (blockMax[row + by] > z) {
                    return false;
                }
            }
        }
        return true;
    }

    /**
     * Recompute block-max bounds for flagged (written-to) blocks, restoring
     * exact maxima so subsequent air-skip tests over freshly cut ground are
     * tight again. Called periodically from #strike and once at its end;
     * cost is proportional to what was actually written, and stale bounds
     * between refreshes are harmless (they only suppress skips).
     */
    #refreshBlocks() {
        const { data, stepsX, stepsY, blocksY, blockMax, blockDirty, dirtyBlocks } = this;
        for (let b of dirtyBlocks) {
            blockDirty[b] = 0;
            const bx = (b / blocksY) | 0,
                by = b - bx * blocksY,
                x0 = bx << BLOCK_SHIFT,
                x1 = Math.min(stepsX, x0 + BLOCK_SIZE),
                y0 = by << BLOCK_SHIFT,
                y1 = Math.min(stepsY, y0 + BLOCK_SIZE);
            let max = -Infinity;
            for (let x = x0; x < x1; x++) {
                const row = x * stepsY;
                for (let y = y0; y < y1; y++) {
                    const v = data[row + y];
                    if (v > max) {
                        max = v;
                    }
                }
            }
            blockMax[b] = max;
        }
        dirtyBlocks.length = 0;
    }

    /**
     * z of the material top surface at world (x,y): bilinear interpolation
     * over the 4 surrounding nodes (same scheme as Probe.toolAtZf,
     * topo3.js:863-899). Outside the widget bounds the stock is untouched,
     * so the stock top z is returned.
     *
     * @returns {number} world z of remaining material surface
     */
    removedTop(x, y) {
        const { data, stepsX, stepsY, stockTop, resolution } = this;
        const tx = this.toGridX(x),
            ty = this.toGridY(y),
            xl = stepsX - 1,
            yl = stepsY - 1;
        if (tx < 0 || tx > xl || ty < 0 || ty > yl) {
            return stockTop;
        }
        const x0 = Math.floor(tx),
            y0 = Math.floor(ty),
            x1 = Math.min(x0 + 1, xl),
            y1 = Math.min(y0 + 1, yl),
            fx = tx - x0,
            fy = ty - y0,
            v00 = data[x0 * stepsY + y0],
            v10 = data[x1 * stepsY + y0],
            v01 = data[x0 * stepsY + y1],
            v11 = data[x1 * stepsY + y1];
        return (v00 * (1 - fx) + v10 * fx) * (1 - fy)
             + (v01 * (1 - fx) + v11 * fx) * fy;
    }

    /**
     * Does material remain at world (x,y,z)?
     *
     * Material occupies [stockBottom, removedTop(x,y)]. A point counts as
     * "having material" when it lies strictly below the remaining surface
     * (the surface itself is the boundary -- no material AT that height).
     * Outside the widget bounds the stock is untouched, so any z within
     * the stock counts as material.
     *
     * @returns {boolean}
     */
    hasMaterial(x, y, z) {
        const top = this.removedTop(x, y);
        if (z >= top) {
            return false;
        }
        const bottom = this.stockBottom;
        return bottom === undefined || z >= bottom;
    }

    /** journal length (convenience for consumers / debugging) */
    get swapCount() {
        return this.swaps.length;
    }

    /**
     * Build the sub-regions of `polys` where the remaining material top is
     * at or below `z` — the areas a tool with its tip at z would sweep
     * through air ("skip cleared" masking between operations).
     *
     * The heightmap is a node lattice; a grid cell counts as cleared only
     * when all four corner nodes are at or below `z` (a cell's bilinear
     * surface never exceeds its corner max, so this test is conservative:
     * borderline cells stay cuttable, never skipped). Cleared cells are
     * run-length merged into horizontal strip rectangles per grid row,
     * which the caller subtracts from its working region with POLY.subtract.
     * A small epsilon folds float noise (identical z computed through
     * different arithmetic paths) into the "already swept" equality case:
     * a surface exactly at tip z removes nothing when re-cut.
     *
     * Nothing here depends on which operations produced the sweeps, so
     * this generalizes intra-op rough-clear masking to any sequence of
     * prior area-clearing ops recorded in the model.
     *
     * @param {Polygon[]} polys region of interest (2D x/y polygons)
     * @param {number} z world z of the effective tool tip. Ops that respect
     * leave stock pass the raised tip (cut plane + leave_z), so the leave
     * skin is never masked as cleared. Flats passes pass the bare cut plane
     * (no leave_z, and strictly below the stock top): their job is to shave
     * the leave_z skin off flat planes, so that skin must not count as
     * already cleared
     * @returns {Polygon[]} cleared strip rectangles (possibly empty)
     */
    clearedRegion(polys, z) {
        const { data, stepsX, stepsY, resolution, minX, minY } = this;
        const thresh = z + CLEAR_EPS;
        // cell (gx,gy) spans nodes gx..gx+1 x gy..gy+1; clamp to the lattice
        const lastCellX = stepsX - 2, lastCellY = stepsY - 2;
        if (lastCellX < 0 || lastCellY < 0 || !polys.length) {
            return [];
        }
        // region of interest in grid coords, clamped to the cell lattice
        let cx0 = lastCellX, cy0 = lastCellY, cx1 = -1, cy1 = -1;
        for (let poly of polys) {
            let b = poly.bounds;
            let lx = Math.max(0, Math.floor(this.toGridX(b.minx))),
                ly = Math.max(0, Math.floor(this.toGridY(b.miny))),
                hx = Math.min(lastCellX, Math.ceil(this.toGridX(b.maxx)) - 1),
                hy = Math.min(lastCellY, Math.ceil(this.toGridY(b.maxy)) - 1);
            if (hx < lx || hy < ly) {
                continue;
            }
            cx0 = Math.min(cx0, lx);
            cy0 = Math.min(cy0, ly);
            cx1 = Math.max(cx1, hx);
            cy1 = Math.max(cy1, hy);
        }
        if (cx1 < cx0) {
            return [];
        }
        const strips = [];
        for (let gy = cy0; gy <= cy1; gy++) {
            // node rows bracketing this cell row
            const nA = gy, nB = gy + 1;
            let run = -1;
            for (let gx = cx0; gx <= cx1 + 1; gx++) {
                const clear = gx <= cx1 &&
                    data[gx * stepsY + nA] <= thresh &&
                    data[(gx + 1) * stepsY + nA] <= thresh &&
                    data[gx * stepsY + nB] <= thresh &&
                    data[(gx + 1) * stepsY + nB] <= thresh;
                if (clear && run < 0) {
                    run = gx;
                } else if (!clear && run >= 0) {
                    // close the run into one strip rectangle at plane z
                    strips.push(newPolygon()
                        .add(minX + run * resolution, minY + gy * resolution, z)
                        .add(minX + gx * resolution, minY + gy * resolution, z)
                        .add(minX + gx * resolution, minY + (gy + 1) * resolution, z)
                        .add(minX + run * resolution, minY + (gy + 1) * resolution, z));
                    run = -1;
                }
            }
        }
        return strips;
    }
}

/**
 * Bucket the profile's writing points by write depth for the air-skip test.
 * A point (dx,dy,dz) writes tipz - dz; with the shallowest stampable tip at
 * `zmin`, points with dz <= zmin - stockTop can never write below the stock
 * top (data never exceeds stockTop) and never lower a cell: they are
 * excluded. Remaining points are bucketed by exact dz value (flat endmill
 * profiles: flute at dz=0 plus a shaft ring at dz=-flute_len); each bucket
 * keeps its extreme offsets, which bound -- exactly, via monotone rounding
 * -- the lattice nodes its points can touch. Continuous-depth profiles
 * (ball/taper) exceed the bucket cap and collapse into a single group
 * spanning every writing point, thresholded by its shallowest write.
 *
 * @param {Float32Array} profile raster tool profile (grid-pixel offsets)
 * @param {number} zmin shallowest tip z the sweep can stamp
 * @param {number} stockTop world z of the untouched stock surface
 * @returns {Array} groups [{dz, x0, x1, y0, y1}] (possibly empty)
 */
function profileAirGroups(profile, zmin, stockTop) {
    const zth = zmin - stockTop;
    const groups = new Map();
    for (let i = 0; i < profile.length; i += 3) {
        const dx = profile[i],
            dy = profile[i + 1],
            dz = profile[i + 2];
        if (dz <= zth) {
            continue;
        }
        let g = groups.get(dz);
        if (!g) {
            groups.set(dz, g = { dz, x0: dx, x1: dx, y0: dy, y1: dy });
        } else {
            if (dx < g.x0) g.x0 = dx; else if (dx > g.x1) g.x1 = dx;
            if (dy < g.y0) g.y0 = dy; else if (dy > g.y1) g.y1 = dy;
        }
    }
    let list = [...groups.values()];
    if (list.length > AIR_GROUP_MAX) {
        let dz = -Infinity,
            x0 = Infinity, x1 = -Infinity,
            y0 = Infinity, y1 = -Infinity;
        for (let i = 0; i < profile.length; i += 3) {
            const dx = profile[i],
                dy = profile[i + 1],
                dzv = profile[i + 2];
            if (dzv <= zth) {
                continue;
            }
            if (dzv > dz) dz = dzv;
            if (dx < x0) x0 = dx; else if (dx > x1) x1 = dx;
            if (dy < y0) y0 = dy; else if (dy > y1) y1 = dy;
        }
        list = [{ dz, x0, x1, y0, y1 }];
    }
    return list;
}

/**
 * Collect the camLines polylines of a sliced OpArea pass. OpArea.slice()
 * accumulates per-area stacks of per-layer slices in `area.areas`, each
 * slice carrying its cutting polylines in `slice.camLines` with the layer z
 * (down lerp planes, flat planes + flatOff, trace depths, leave_z lifts, tab
 * lifts) already baked into the point z values.
 *
 * @param {OpArea} area a pass instance, post-slice()
 * @returns {Array} flat list of camLines polylines (possibly empty)
 */
export function areaPassCamLines(area) {
    return (area?.areas ?? [])
        .flat()
        .filter(s => s.camLines && s.camLines.length)
        .map(s => s.camLines)
        .flat();
}

/**
 * Record one pass of an OpArea-based op into the widget's stock removal
 * model. Shared by every camLines-producing op (rough since phase 1,
 * outline/trace/pocket/contour since phase 2): the sweep is the
 * max-convolution of the op tool's raster profile along the pass camLines,
 * folded by StockModel.#strike() which filters points at or above the stock
 * top (plunges from above only start cutting below the surface, retracts
 * and traverses never touch). Tab/clamp lifts and ov_topz/ov_botz are
 * already baked into the recorded points by the generating op.
 *
 * leave (xy) and leave_z are journalled as pass parameters. leave_xy is
 * inherently respected by the sweep when the op insets its centerlines by
 * tool radius + leave (clear mode firstOff, trace offsets), so the profile
 * convolution never reaches the leave shell — the model records the actual
 * sweep, not the theoretical full removal.
 *
 * 4th axis work (state.isIndexed) rotates the widget out of the heightmap's
 * unrotated XY frame: the model is marked invalid so consumers fall back to
 * model-less behavior instead of trusting an empty (fully-stock) map.
 *
 * @param {Object} state shared CAM op state (slice.js); must carry
 *   stockModel, settings, isIndexed
 * @param {string} type op type for the journal record ("rough",
 *   "outline", "trace", "pocket", "contour", ...)
 * @param {Object} conf pass parameters: { tool, mode, rename, thru, down,
 *   leave, leave_xy, leave_z, ov_topz, ov_botz } — missing fields journal
 *   as undefined
 * @param {OpArea|Array} area a sliced OpArea pass, or a ready-made flat
 *   camLines array (contour's topo slices)
 * @param {Function} [onProgress] optional 0..1 callback invoked while the
 *   sweep is folded into the heightmap (stock-scale sweeps take seconds
 *   even sampled; without it the slice progress bar freezes)
 * @returns {Object|undefined} the journal record, or undefined when nothing
 *   was recorded (no model, invalid model, no camLines)
 */
export function recordAreaSweep(state, type, conf, area, onProgress) {
    const stockModel = state.stockModel;
    if (!stockModel) {
        return undefined;
    }
    if (state.isIndexed) {
        stockModel.valid = false;
        return undefined;
    }
    if (!stockModel.valid) {
        return undefined;
    }
    const camLines = Array.isArray(area) ? area : areaPassCamLines(area);
    if (!camLines.length) {
        return undefined;
    }
    // dedicated instance so generateProfile (below) doesn't leave the op
    // tool's cached profile at the stock model's resolution
    const tool = new Tool(state.settings, conf.tool);
    return stockModel.recordSweep({
        type,
        mode: conf.mode,
        rename: conf.rename,
        thru: conf.thru,
        tool,
        profile: tool.generateProfile(stockModel.resolution).profile,
        camLines,
        down: conf.down,
        leave: conf.leave_xy ?? conf.leave,
        leave_z: conf.leave_z,
        ov_topz: conf.ov_topz,
        ov_botz: conf.ov_botz,
        onProgress
    });
}

/**
 * Grid resolution (mm per cell) for the stock removal model, decoupled from
 * `controller.animesh` (which sizes the topo/animation mesh — a much finer
 * need than sweep recording, and quadratically expensive here).
 *
 * Selection order:
 *   1. explicit `controller.stockRes` (mm/cell) when > 0 — user override;
 *   2. hybrid auto: proportional to the smallest flute diameter among
 *      sweep-recording ops' tools (minDia / 8, so the tool footprint spans
 *      >= 8 grid pixels and swept bands stay gapless), clamped to
 *      [STOCK_RES_MIN, STOCK_RES_MAX], then coarsened if needed so neither
 *      lattice axis exceeds STOCK_STEPS_MAX nodes (size cap);
 *   3. STOCK_RES_DEFAULT when no sweep op has a usable tool.
 *
 * @param {Object} settings full CAM settings
 * @param {Object} bounds widget bounding box {min:{x,y,z}, max:{x,y,z}}
 * @returns {number} resolution in mm per grid cell
 */
export function stockResolution(settings, bounds) {
    const { process = {}, controller = {} } = settings || {};
    const boundsX = bounds.max.x - bounds.min.x;
    const boundsY = bounds.max.y - bounds.min.y;

    // explicit user override (0/blank/undefined = auto)
    const stockRes = parseFloat(controller.stockRes);
    if (stockRes > 0) {
        return stockRes.round(5);
    }

    // smallest sweep-recording tool across the (enabled) op list
    let minDia = 0;
    for (let op of process.ops || []) {
        if (op.disabled || !SWEEP_OPS.has(op.type)) {
            continue;
        }
        const dia = new Tool(settings, op.tool).fluteDiameter();
        if (dia > 0 && (minDia === 0 || dia < minDia)) {
            minDia = dia;
        }
    }

    let res = minDia > 0 ? minDia / 8 : STOCK_RES_DEFAULT;
    res = Math.min(STOCK_RES_MAX, Math.max(STOCK_RES_MIN, res));
    // size cap: never let a lattice axis outgrow the node cap
    res = Math.max(res, boundsX / STOCK_STEPS_MAX, boundsY / STOCK_STEPS_MAX);
    return res.round(5);
}

/**
 * Cache factory: returns the widget's StockModel, creating it when absent
 * or invalidated (same pattern as widget.topo in topo3.js:61-79). The cache
 * fingerprint covers the op list, stock setup, widget bounds and the grid
 * resolution, so any settings change produces a fresh model.
 *
 * @param {Object} settings full CAM settings
 * @param {Widget} widget
 * @param {Object} opt { stockTop, stockBottom, tolerance?, resolution? }
 * @returns {StockModel}
 */
export function getStockModel(settings, widget, opt = {}) {
    const { process = {}, controller = {} } = settings;
    const bounds = widget.getBoundingBox();
    const tolerance = opt.tolerance ?? 0;
    const stockTop = opt.stockTop;
    const stockBottom = opt.stockBottom;

    // grid resolution is decoupled from controller.animesh: explicit
    // opt.resolution wins, otherwise controller.stockRes (mm/cell) or the
    // hybrid auto selection scaled to the smallest sweep tool (see
    // stockResolution)
    const resolution = opt.resolution > 0
        ? opt.resolution
        : stockResolution(settings, bounds);

    // fingerprint: op list + stock dims + bounds + resolution inputs.
    // the resolved resolution is included (not just controller.stockRes)
    // so tool-library edits that shift the auto value also invalidate;
    // animesh is intentionally absent — it no longer feeds the grid
    const fingerprint = [
        JSON.stringify(process.ops || []),
        process.camStockX, process.camStockY, process.camStockZ, process.camStockOffset,
        bounds.min.x, bounds.min.y, bounds.max.x, bounds.max.y,
        tolerance,
        resolution,
        controller.stockRes ?? 0,
        stockTop, stockBottom
    ].join('|');

    const cached = widget.stockModel;
    if (cached && cached.fingerprint === fingerprint) {
        return cached;
    }

    return widget.stockModel = new StockModel({
        widget,
        bounds,
        tolerance,
        resolution,
        stockTop,
        stockBottom,
        fingerprint
    });
}
