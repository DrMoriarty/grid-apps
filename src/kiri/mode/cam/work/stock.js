import { Tool } from '../core/tool.js';
import { newPolygon } from '../../../../geo/polygon.js';

/**
 * CAM stock removal model (Phase 1 skeleton).
 *
 * Maintains a per-widget "removed top" heightmap: for each grid node over the
 * widget bounds it stores the z of the material surface *after* all recorded
 * tool sweeps. Untouched nodes hold the stock top z, so the map doubles as
 * "current material top". Served from a SharedArrayBuffer (same pattern as
 * `widget.topo.data` in topo3.js) so worker code and main thread can share it.
 *
 * Data model conventions:
 *   - grid node (gx,gy) maps to world (minX + gx*resolution, minY + gy*resolution),
 *     same convention as the topo raster (see topo3.js crossR_sync comment);
 *   - cell index = gx * stepsY + gy, same as Probe.toolAtZ;
 *   - tool profiles are raster profiles generated by
 *     `Tool.generateProfile(resolution)` at THIS model's resolution, i.e.
 *     profile offsets are in grid pixels with dz <= 0 below the tool tip,
 *     identical to what Probe consumes.
 *
 * Recording a sweep is the inverse of Probe.toolAtZ (topo3.js:826-855).
 * toolAtZ answers "what tip z does terrain force" via the constraint
 * T >= dz + terrain for every profile point. Inverting it, a tool with tip
 * at T leaves terrain at T - dz in every covered cell (dz <= 0 is the
 * profile point's depth below the tip, so T - dz is the cutter underside
 * z at that offset): flat endmill -> T everywhere in the flute disc, ball
 * -> a bowl, shaft points (dz = -flute_len, above the tip) write above T
 * and thus never cut. Folding a sweep into the grid keeps the deepest
 * engagement per cell: data[cell] = min(data[cell], tipz - dz), the same
 * profile convolution loop as toolAtZ with max/min flipped.
 *
 * Scope note: this is skeleton + API only. Consumers (ops recording sweeps,
 * views querying removal) are wired in follow-up tasks.
 */

// ops whose motion happens in rotated stock space: their camLines cannot be
// projected onto the XY heightmap, so recording one marks the model invalid
// and consumers must fall back to current (model-less) behavior
const ROTARY_OPS = new Set(['index', 'lathe']);

// bilinear boundary snap epsilon (fraction of a cell)
const EPS = 1e-6;

// tolerance for "material top at or below tip z" comparisons in
// clearedRegion (mm): z values converge on the same plane through
// different lerp/add paths, so exact equality is unreliable; anything
// within this margin counts as already swept
const CLEAR_EPS = 0.001;

export class StockModel {

    /**
     * @param {Object} opt
     * @param {Widget} opt.widget owning widget (for cache attachment by caller)
     * @param {Object} opt.bounds widget bounding box {min:{x,y,z}, max:{x,y,z}}
     * @param {number} [opt.tolerance] grid resolution in mm; when 0/undefined
     *   derived from animation mesh density using the topo3.js:46 formula
     * @param {number} opt.stockTop world z of the stock top surface
     * @param {number} [opt.stockBottom] world z of the stock bottom surface
     * @param {string} [opt.fingerprint] cache validity fingerprint
     */
    constructor(opt) {
        const bounds = opt.bounds;
        const boundsX = bounds.max.x - bounds.min.x;
        const boundsY = bounds.max.y - bounds.min.y;
        const tolerance = opt.tolerance > 0 ? opt.tolerance : 0;

        // same auto-resolution formula as topo3.js:46 (animesh = 100 * 2500)
        const animesh = parseInt(opt.animesh || 100) * 2500;
        const resolution = (tolerance
            ? tolerance
            : 1 / Math.sqrt(animesh / (boundsX * boundsY))
        ).round(5);

        // +1 so the node lattice covers maxX/maxY exactly
        const stepsX = Math.ceil(boundsX / resolution) + 1;
        const stepsY = Math.ceil(boundsY / resolution) + 1;

        this.widget = opt.widget;
        this.bounds = bounds;
        this.minX = bounds.min.x;
        this.minY = bounds.min.y;
        this.tolerance = tolerance;
        this.resolution = resolution;
        this.stepsX = stepsX;
        this.stepsY = stepsY;
        this.stockTop = opt.stockTop;
        this.stockBottom = opt.stockBottom;
        this.fingerprint = opt.fingerprint;

        /** validity flag: false once a rotary op sweep was recorded */
        this.valid = true;

        /**
         * sweep journal: raw records for future visualizations (Phase 3).
         * each record: { seq, type, mode, rename, thru, tool, profile,
         *                camLines, down, leave, leave_z, ov_topz, ov_botz,
         *                valid }
         * @type {Array<Object>}
         */
        this.swaps = [];

        // removed-top heightmap, initialized to full stock
        this.data = new Float32Array(new SharedArrayBuffer(stepsX * stepsY * 4));
        this.data.fill(opt.stockTop);
    }

    /** world x,y -> fractional grid coords */
    toGridX(x) {
        return (x - this.minX) / this.resolution;
    }

    toGridY(y) {
        return (y - this.minY) / this.resolution;
    }

    /**
     * Record one toolpath sweep into the model.
     *
     * @param {Object} rec sweep descriptor:
     *   type     {string} op type ("rough", "outline", "index", ...)
     *   mode     {string} op sub-mode ("clear", "trace", ...) (optional)
     *   rename   {string} op rename / layer name (optional)
     *   thru     {boolean} trace passes through stock bottom (optional)
     *   tool     {Tool}   op tool (optional if profile given)
     *   profile  {Float32Array} raster tool profile from
     *            Tool.generateProfile(this.resolution).profile
     *   camLines {Array} polylines of points with x,y,z in world coords
     *   down, leave, leave_z, ov_topz, ov_botz {any} raw op params, journalled
     * @returns {Object} the journal record
     */
    recordSweep(rec) {
        const entry = {
            seq: this.swaps.length,
            type: rec.type,
            mode: rec.mode,
            rename: rec.rename,
            thru: rec.thru,
            tool: rec.tool,
            profile: rec.profile ?? rec.tool?.profile,
            camLines: rec.camLines,
            down: rec.down,
            leave: rec.leave,
            leave_z: rec.leave_z,
            ov_topz: rec.ov_topz,
            ov_botz: rec.ov_botz,
            valid: this.valid
        };
        this.swaps.push(entry);

        if (ROTARY_OPS.has(rec.type)) {
            // rotary motion cannot be folded into the XY heightmap:
            // mark invalid, keep the journal record, change nothing else
            this.valid = false;
            entry.valid = false;
            return entry;
        }

        const profile = entry.profile;
        if (!profile || !rec.camLines) {
            return entry;
        }

        this.#strike(rec.camLines, profile);
        return entry;
    }

    /**
     * Fold a set of world-space polylines through a tool profile into the
     * heightmap. Only milling motion removes material: tool positions whose
     * tip z is at or above the stock top remove nothing (plunges from above
     * only start cutting once below the surface, retracts/traverses never
     * touch). Tab/clamp lifts and ov_topz/ov_botz are already baked into
     * camLines by the time they are recorded, so no extra handling here.
     *
     * @param {Array} camLines polylines (Polygon or point array, points with x,y,z)
     * @param {Float32Array} profile raster tool profile (grid-pixel offsets)
     */
    #strike(camLines, profile) {
        const { stockTop, resolution } = this;
        const maxStep = resolution;
        for (let line of camLines) {
            const pts = line.points || line;
            if (!pts || pts.length === 0) {
                continue;
            }
            // single-point line (e.g. drill mark): stamp directly
            if (pts.length === 1) {
                const p = pts[0];
                if (p.z < stockTop) {
                    this.#stamp(p.x, p.y, p.z, profile);
                }
                continue;
            }
            let prev = pts[0];
            for (let i = 1; i < pts.length; i++) {
                const p = pts[i];
                const dx = p.x - prev.x,
                    dy = p.y - prev.y,
                    dist = Math.sqrt(dx * dx + dy * dy),
                    // subdivide long segments so the swept surface has no gaps
                    n = Math.max(1, Math.ceil(dist / maxStep));
                for (let s = 0; s <= n; s++) {
                    const t = s / n,
                        z = prev.z + (p.z - prev.z) * t;
                    // z filter: above the stock surface nothing is removed
                    if (z >= stockTop) {
                        continue;
                    }
                    this.#stamp(
                        prev.x + dx * t,
                        prev.y + dy * t,
                        z,
                        profile
                    );
                }
                prev = p;
            }
        }
    }

    /**
     * Fold one tool position into the heightmap. Inverse of Probe.toolAtZ:
     * profile point (dx,dy,dz) covers grid node (gx+dx, gy+dy) and the
     * cutter underside there sits at tipz - dz (dz <= 0). The deepest
     * engagement wins per cell, so writes are min-merged into data.
     * tipz is already filtered against stockTop by the caller, and since
     * dz <= 0 for cutting points, a stamp can never write above stockTop.
     */
    #stamp(x, y, tipz, profile) {
        const { data, stepsX, stepsY, resolution } = this;
        const gx = this.toGridX(x),
            gy = this.toGridY(y);
        let i = 0;
        while (i < profile.length) {
            const tx = Math.round(profile[i++] + gx),
                ty = Math.round(profile[i++] + gy),
                tz = tipz - profile[i++];
            if (tx < 0 || tx >= stepsX || ty < 0 || ty >= stepsY) {
                continue;
            }
            const idx = tx * stepsY + ty;
            if (tz < data[idx]) {
                data[idx] = tz;
            }
        }
    }

    /**
     * z of the material top surface at world (x,y): bilinear interpolation
     * over the 4 surrounding nodes (same scheme as Probe.toolAtZf,
     * topo3.js:863-899). Outside the widget bounds the stock is untouched,
     * so the stock top z is returned.
     *
     * @returns {number} world z of remaining material surface
     */
    removedTop(x, y) {
        const { data, stepsX, stepsY, stockTop, resolution } = this;
        const tx = this.toGridX(x),
            ty = this.toGridY(y),
            xl = stepsX - 1,
            yl = stepsY - 1;
        if (tx < 0 || tx > xl || ty < 0 || ty > yl) {
            return stockTop;
        }
        const x0 = Math.floor(tx),
            y0 = Math.floor(ty),
            x1 = Math.min(x0 + 1, xl),
            y1 = Math.min(y0 + 1, yl),
            fx = tx - x0,
            fy = ty - y0,
            v00 = data[x0 * stepsY + y0],
            v10 = data[x1 * stepsY + y0],
            v01 = data[x0 * stepsY + y1],
            v11 = data[x1 * stepsY + y1];
        return (v00 * (1 - fx) + v10 * fx) * (1 - fy)
             + (v01 * (1 - fx) + v11 * fx) * fy;
    }

    /**
     * Does material remain at world (x,y,z)?
     *
     * Material occupies [stockBottom, removedTop(x,y)]. A point counts as
     * "having material" when it lies strictly below the remaining surface
     * (the surface itself is the boundary -- no material AT that height).
     * Outside the widget bounds the stock is untouched, so any z within
     * the stock counts as material.
     *
     * @returns {boolean}
     */
    hasMaterial(x, y, z) {
        const top = this.removedTop(x, y);
        if (z >= top) {
            return false;
        }
        const bottom = this.stockBottom;
        return bottom === undefined || z >= bottom;
    }

    /** journal length (convenience for consumers / debugging) */
    get swapCount() {
        return this.swaps.length;
    }

    /**
     * Build the sub-regions of `polys` where the remaining material top is
     * at or below `z` — the areas a tool with its tip at z would sweep
     * through air ("skip cleared" masking between operations).
     *
     * The heightmap is a node lattice; a grid cell counts as cleared only
     * when all four corner nodes are at or below `z` (a cell's bilinear
     * surface never exceeds its corner max, so this test is conservative:
     * borderline cells stay cuttable, never skipped). Cleared cells are
     * run-length merged into horizontal strip rectangles per grid row,
     * which the caller subtracts from its working region with POLY.subtract.
     * A small epsilon folds float noise (identical z computed through
     * different arithmetic paths) into the "already swept" equality case:
     * a surface exactly at tip z removes nothing when re-cut.
     *
     * Nothing here depends on which operations produced the sweeps, so
     * this generalizes intra-op rough-clear masking to any sequence of
     * prior area-clearing ops recorded in the model.
     *
     * @param {Polygon[]} polys region of interest (2D x/y polygons)
     * @param {number} z world z of the effective tool tip (cut plane + leave_z)
     * @returns {Polygon[]} cleared strip rectangles (possibly empty)
     */
    clearedRegion(polys, z) {
        const { data, stepsX, stepsY, resolution, minX, minY } = this;
        const thresh = z + CLEAR_EPS;
        // cell (gx,gy) spans nodes gx..gx+1 x gy..gy+1; clamp to the lattice
        const lastCellX = stepsX - 2, lastCellY = stepsY - 2;
        if (lastCellX < 0 || lastCellY < 0 || !polys.length) {
            return [];
        }
        // region of interest in grid coords, clamped to the cell lattice
        let cx0 = lastCellX, cy0 = lastCellY, cx1 = -1, cy1 = -1;
        for (let poly of polys) {
            let b = poly.bounds;
            let lx = Math.max(0, Math.floor(this.toGridX(b.minx))),
                ly = Math.max(0, Math.floor(this.toGridY(b.miny))),
                hx = Math.min(lastCellX, Math.ceil(this.toGridX(b.maxx)) - 1),
                hy = Math.min(lastCellY, Math.ceil(this.toGridY(b.maxy)) - 1);
            if (hx < lx || hy < ly) {
                continue;
            }
            cx0 = Math.min(cx0, lx);
            cy0 = Math.min(cy0, ly);
            cx1 = Math.max(cx1, hx);
            cy1 = Math.max(cy1, hy);
        }
        if (cx1 < cx0) {
            return [];
        }
        const strips = [];
        for (let gy = cy0; gy <= cy1; gy++) {
            // node rows bracketing this cell row
            const nA = gy, nB = gy + 1;
            let run = -1;
            for (let gx = cx0; gx <= cx1 + 1; gx++) {
                const clear = gx <= cx1 &&
                    data[gx * stepsY + nA] <= thresh &&
                    data[(gx + 1) * stepsY + nA] <= thresh &&
                    data[gx * stepsY + nB] <= thresh &&
                    data[(gx + 1) * stepsY + nB] <= thresh;
                if (clear && run < 0) {
                    run = gx;
                } else if (!clear && run >= 0) {
                    // close the run into one strip rectangle at plane z
                    strips.push(newPolygon()
                        .add(minX + run * resolution, minY + gy * resolution, z)
                        .add(minX + gx * resolution, minY + gy * resolution, z)
                        .add(minX + gx * resolution, minY + (gy + 1) * resolution, z)
                        .add(minX + run * resolution, minY + (gy + 1) * resolution, z));
                    run = -1;
                }
            }
        }
        return strips;
    }
}

/**
 * Collect the camLines polylines of a sliced OpArea pass. OpArea.slice()
 * accumulates per-area stacks of per-layer slices in `area.areas`, each
 * slice carrying its cutting polylines in `slice.camLines` with the layer z
 * (down lerp planes, flat planes + flatOff, trace depths, leave_z lifts, tab
 * lifts) already baked into the point z values.
 *
 * @param {OpArea} area a pass instance, post-slice()
 * @returns {Array} flat list of camLines polylines (possibly empty)
 */
export function areaPassCamLines(area) {
    return (area?.areas ?? [])
        .flat()
        .filter(s => s.camLines && s.camLines.length)
        .map(s => s.camLines)
        .flat();
}

/**
 * Record one pass of an OpArea-based op into the widget's stock removal
 * model. Shared by every camLines-producing op (rough since phase 1,
 * outline/trace/pocket/contour since phase 2): the sweep is the
 * max-convolution of the op tool's raster profile along the pass camLines,
 * folded by StockModel.#strike() which filters points at or above the stock
 * top (plunges from above only start cutting below the surface, retracts
 * and traverses never touch). Tab/clamp lifts and ov_topz/ov_botz are
 * already baked into the recorded points by the generating op.
 *
 * leave (xy) and leave_z are journalled as pass parameters. leave_xy is
 * inherently respected by the sweep when the op insets its centerlines by
 * tool radius + leave (clear mode firstOff, trace offsets), so the profile
 * convolution never reaches the leave shell — the model records the actual
 * sweep, not the theoretical full removal.
 *
 * 4th axis work (state.isIndexed) rotates the widget out of the heightmap's
 * unrotated XY frame: the model is marked invalid so consumers fall back to
 * model-less behavior instead of trusting an empty (fully-stock) map.
 *
 * @param {Object} state shared CAM op state (slice.js); must carry
 *   stockModel, settings, isIndexed
 * @param {string} type op type for the journal record ("rough",
 *   "outline", "trace", "pocket", "contour", ...)
 * @param {Object} conf pass parameters: { tool, mode, rename, thru, down,
 *   leave, leave_xy, leave_z, ov_topz, ov_botz } — missing fields journal
 *   as undefined
 * @param {OpArea|Array} area a sliced OpArea pass, or a ready-made flat
 *   camLines array (contour's topo slices)
 * @returns {Object|undefined} the journal record, or undefined when nothing
 *   was recorded (no model, invalid model, no camLines)
 */
export function recordAreaSweep(state, type, conf, area) {
    const stockModel = state.stockModel;
    if (!stockModel) {
        return undefined;
    }
    if (state.isIndexed) {
        stockModel.valid = false;
        return undefined;
    }
    if (!stockModel.valid) {
        return undefined;
    }
    const camLines = Array.isArray(area) ? area : areaPassCamLines(area);
    if (!camLines.length) {
        return undefined;
    }
    // dedicated instance so generateProfile (below) doesn't leave the op
    // tool's cached profile at the stock model's resolution
    const tool = new Tool(state.settings, conf.tool);
    return stockModel.recordSweep({
        type,
        mode: conf.mode,
        rename: conf.rename,
        thru: conf.thru,
        tool,
        profile: tool.generateProfile(stockModel.resolution).profile,
        camLines,
        down: conf.down,
        leave: conf.leave_xy ?? conf.leave,
        leave_z: conf.leave_z,
        ov_topz: conf.ov_topz,
        ov_botz: conf.ov_botz
    });
}

/**
 * Cache factory: returns the widget's StockModel, creating it when absent
 * or invalidated (same pattern as widget.topo in topo3.js:61-79). The cache
 * fingerprint covers the op list, stock setup, widget bounds and grid
 * resolution source, so any settings change produces a fresh model.
 *
 * @param {Object} settings full CAM settings
 * @param {Widget} widget
 * @param {Object} opt { stockTop, stockBottom, tolerance?, animesh? }
 * @returns {StockModel}
 */
export function getStockModel(settings, widget, opt = {}) {
    const { process = {}, controller = {} } = settings;
    const bounds = widget.getBoundingBox();
    const tolerance = opt.tolerance ?? 0;
    const stockTop = opt.stockTop;
    const stockBottom = opt.stockBottom;

    // fingerprint: op list + stock dims + bounds + resolution inputs.
    // any change re-creates the model (invalidation on ops/settings change)
    const fingerprint = [
        JSON.stringify(process.ops || []),
        process.camStockX, process.camStockY, process.camStockZ, process.camStockOffset,
        bounds.min.x, bounds.min.y, bounds.max.x, bounds.max.y,
        tolerance,
        opt.animesh ?? controller.animesh,
        stockTop, stockBottom
    ].join('|');

    const cached = widget.stockModel;
    if (cached && cached.fingerprint === fingerprint) {
        return cached;
    }

    return widget.stockModel = new StockModel({
        widget,
        bounds,
        tolerance,
        animesh: opt.animesh ?? controller.animesh,
        stockTop,
        stockBottom,
        fingerprint
    });
}
